#!/usr/bin/env bash
# Generates jobs/<model>_<agent>_<env>.sh for every model x agent x env combination in config.sh
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
source "$HERE/config.sh"
mkdir -p "$HERE/jobs"
rm -f "$HERE"/jobs/*.sh

n=0
for line in "${MODELS[@]}"; do
  IFS='|' read -r tag client base model keyvar workers extra model_envs <<< "$line"
  if [[ -n "${model_envs:-}" ]]; then read -ra these_envs <<< "$model_envs"; else these_envs=("${ENVS[@]}"); fi
  for agent in "${AGENT_TYPES[@]}"; do
    for env in "${these_envs[@]}"; do
      job="$HERE/jobs/${tag}_${agent}_${env}.sh"

      budget=""
      if [[ "$FULL" != "1" ]]; then
        budget="eval.num_episodes.${env}=${EPISODES[$env]}"
        [[ -n "${MAX_STEPS[$env]}" ]] && budget+=" eval.max_steps_per_episode=${MAX_STEPS[$env]}"
      fi
      base_arg=""; [[ "$base" != "-" ]] && base_arg="client.base_url=$base"
      key_line=""; [[ "$keyvar" != "-" && "$client" != "gemini" ]] && key_line="export OPENAI_API_KEY=\"\${$keyvar:?$keyvar not set in \$KEYS_FILE}\""

      cat > "$job" <<EOF
#!/usr/bin/env bash
# Auto-generated by make_jobs.sh: model=$tag ($model), agent=$agent, env=$env
set -uo pipefail
HERE="\$(cd "\$(dirname "\$0")/.." && pwd)"
source "\$HERE/config.sh"
[[ -f "\$KEYS_FILE" ]] && source "\$KEYS_FILE"
if [[ -n "\$CONDA_ENV" ]]; then
  source "\$(conda info --base)/etc/profile.d/conda.sh" && conda activate "\$CONDA_ENV"
fi
$key_line
cd "\$BALROG_DIR"
OUT="\$RESULTS_DIR/$tag/$agent/$env"
mkdir -p "\$OUT"
# Resume the most recent run in \$OUT (BALROG skips episodes that already have a .json).
# Start fresh instead with:  FRESH=1 ./run_all.sh <model>
RESUME=""
LAST="\$(ls -d "\$OUT"/*/ 2>/dev/null | sort | tail -1)"
if [[ -n "\$LAST" && "\${FRESH:-0}" != "1" ]]; then
  LAST="\${LAST%/}"
  [[ -f "\$LAST/eval.log" ]] && cp "\$LAST/eval.log" "\$LAST/eval.log.bak_\$(date +%m%d_%H%M)"
  RESUME="eval.resume_from=\$LAST"
  echo "resuming \$LAST"
fi
echo "[\$(date '+%F %T')] START $tag/$agent/$env"
python eval.py \\
  agent.type=$agent \$AGENT_ARGS \\
  envs.names=$env \\
  client.client_name=$client client.model_id=$model $base_arg \\
  eval.num_workers=$workers eval.output_dir="\$OUT" \$RESUME \\
  $budget $extra
rc=\$?
# eval.py exits 0 even when every API call failed; treat "no finished episodes" as a failure
RUN="\$(ls -d "\$OUT"/*/ 2>/dev/null | sort | tail -1)"
n_ep=\$(find "\$RUN" -name '*_run_*.json' 2>/dev/null | wc -l)
echo "finished episodes in \$RUN: \$n_ep"
[[ \$rc -eq 0 && \$n_ep -eq 0 ]] && rc=2
echo "[\$(date '+%F %T')] END $tag/$agent/$env (exit \$rc)"
exit \$rc
EOF
      chmod +x "$job"
      n=$((n+1))
    done
  done
done
echo "Wrote $n job files to $HERE/jobs/"