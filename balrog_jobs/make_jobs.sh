#!/usr/bin/env bash
# Generates jobs/<model>_<env>.sh for every model x env combination in config.sh
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
source "$HERE/config.sh"
mkdir -p "$HERE/jobs"
rm -f "$HERE"/jobs/*.sh

n=0
for line in "${MODELS[@]}"; do
  IFS='|' read -r tag client base model keyvar workers extra <<< "$line"
  for env in "${ENVS[@]}"; do
    job="$HERE/jobs/${tag}_${env}.sh"

    budget=""
    if [[ "$FULL" != "1" ]]; then
      budget="eval.num_episodes.${env}=${EPISODES[$env]}"
      [[ -n "${MAX_STEPS[$env]}" ]] && budget+=" eval.max_steps_per_episode=${MAX_STEPS[$env]}"
    fi
    base_arg=""; [[ "$base" != "-" ]] && base_arg="client.base_url=$base"
    key_line=""; [[ "$keyvar" != "-" && "$client" != "gemini" ]] && key_line="export OPENAI_API_KEY=\"\${$keyvar:?$keyvar not set in \$KEYS_FILE}\""

    cat > "$job" <<EOF
#!/usr/bin/env bash
# Auto-generated by make_jobs.sh: model=$tag ($model), env=$env
set -uo pipefail
HERE="\$(cd "\$(dirname "\$0")/.." && pwd)"
source "\$HERE/config.sh"
[[ -f "\$KEYS_FILE" ]] && source "\$KEYS_FILE"
if [[ -n "\$CONDA_ENV" ]]; then
  source "\$(conda info --base)/etc/profile.d/conda.sh" && conda activate "\$CONDA_ENV"
fi
$key_line
cd "\$BALROG_DIR"
OUT="\$RESULTS_DIR/$tag/$env"
mkdir -p "\$OUT"
echo "[\$(date '+%F %T')] START $tag/$env"
python eval.py \\
  agent.type=\$AGENT_TYPE \$AGENT_ARGS \\
  envs.names=$env \\
  client.client_name=$client client.model_id=$model $base_arg \\
  eval.num_workers=$workers eval.output_dir="\$OUT" \\
  $budget $extra
rc=\$?
echo "[\$(date '+%F %T')] END $tag/$env (exit \$rc)"
exit \$rc
EOF
    chmod +x "$job"
    n=$((n+1))
  done
done
echo "Wrote $n job files to $HERE/jobs/"
